let targetLanguage: Language = "en";

const textOriginals = new WeakMap<Node, { orig: string; out: string }>();
const attrOriginals = new WeakMap<Element, Record<string, { orig: string; out: string }>>();
const translatedAttributes = ["aria-label", "placeholder", "title", "alt"];

function translateText(value: string): string {
  const trimmed = value.trim();
  if (!trimmed) return value;
  const dictionary = targetLanguage === "fi" ? fiExact : exact;
  const rules = targetLanguage === "fi" ? fiPatterns : patterns;
  const lead = value.slice(0, value.indexOf(trimmed));
  const tail = value.slice(lead.length + trimmed.length);
  if (Object.prototype.hasOwnProperty.call(dictionary, trimmed)) return lead + dictionary[trimmed] + tail;
  for (const [pattern, template] of rules) {
    if (pattern.test(trimmed)) {
      const out = trimmed.replace(pattern, (...args: unknown[]) => {
        const groups = args.slice(1).filter((arg) => typeof arg === "string" || arg === undefined) as (string | undefined)[];
        return template.replace(/\$(\d)/g, (_, index: string) => translateText(groups[Number(index) - 1] ?? ""));
      });
      return lead + out + tail;
    }
  }
  return value;
}
function translateTextNode(node: Text) {
  const record = textOriginals.get(node);
  if (record && node.data === record.out) return;
  const out = translateText(node.data);
  if (out !== node.data) {
    textOriginals.set(node, { orig: node.data, out });
    node.data = out;
  }
}

function translateAttribute(element: Element, name: string) {
  const value = element.getAttribute(name);
  if (!value) return;
  const records = attrOriginals.get(element) ?? {};
  if (records[name] && records[name].out === value) return;
  const out = translateText(value);
  if (out !== value) {
    records[name] = { orig: value, out };
    attrOriginals.set(element, records);
    element.setAttribute(name, out);
  }
}

function walk(root: Node, visit: (node: Node) => void) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
  let node: Node | null = root;
  while (node) {
    visit(node);
    node = walker.nextNode();
  }
}

function translateTree(root: Node) {
  walk(root, (node) => {
    if (node.nodeType === Node.TEXT_NODE) translateTextNode(node as Text);
    else if (node.nodeType === Node.ELEMENT_NODE) {
      const tag = (node as Element).tagName;
      if (tag === "SCRIPT" || tag === "STYLE") return;
      translatedAttributes.forEach((name) => translateAttribute(node as Element, name));
    }
  });
}

function restoreTree(root: Node) {
  walk(root, (node) => {
    if (node.nodeType === Node.TEXT_NODE) {
      const record = textOriginals.get(node);
      if (record && (node as Text).data === record.out) (node as Text).data = record.orig;
      textOriginals.delete(node);
    } else if (node.nodeType === Node.ELEMENT_NODE) {
      const element = node as Element;
      const records = attrOriginals.get(element);
      if (records) {
        Object.entries(records).forEach(([name, record]) => {
          if (element.getAttribute(name) === record.out) element.setAttribute(name, record.orig);
        });
        attrOriginals.delete(element);
      }
    }
  });
}

let observer: MutationObserver | null = null;

export function applyLanguage(language: Language) {
  observer?.disconnect();
  observer = null;
  restoreTree(document.body);
  targetLanguage = language;
  translateTree(document.body);
  observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === "characterData") translateTextNode(mutation.target as Text);
      else if (mutation.type === "attributes") translateAttribute(mutation.target as Element, mutation.attributeName ?? "");
      else mutation.addedNodes.forEach((added) => translateTree(added));
    }
  });
  observer.observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: translatedAttributes });
}
